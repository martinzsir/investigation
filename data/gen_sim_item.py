"""
data/gen_sim_item.py —— 重点物品演示数据（物品台账 + 持有流水）。

为什么用 DuckDB 写 parquet 而不是 pandas.to_parquet
------------------------------------------------
本环境缺 pyarrow（pandas 写 parquet 的后端），而 duckdb 自带 parquet
writer。装 pyarrow 有触发沙盒重置的先例（装 python-multipart 时 pytest/
duckdb 全部丢失），故不引入新依赖。

演示数据覆盖的四条业务形态（每条都对应设计里的一条红线）
------------------------------------------------
1. **流转**：浙A12345 由王五 → 李志强。只画静态边会读成"两人共用一辆车"，
   实际是买卖——时态边（start/end）是这条边能被正确理解的前提。
2. **重叠即冲突**：王五名下另有一段 2021-08-01~2022-01-31，与李志强的
   2021-07-01~ 相交。这不是"数据噪声"，是过户异常／套牌线索本身（重号是
   信号，与人的重名是噪声恰好相反）。
3. **错序**：发票登记序号 0 的时间晚于序号 1——台账录入顺序与权属时间矛盾，
   是倒签／虚假登记的线索。判据只报矛盾，**绝不按时间重排**（重排会把信号
   抹掉）。
4. **无凭证不合并**：两件涉案物品（双肩包／U盘）无凭证，只靠 descriptors
   成实体。若统一给空 digest，会被静默合并成一件（D4）。

另有一条 **不可判定**：王五另有一条起止皆空的持有。缺区间绝不静默当成
"无约束"（那等于"一直持有"），必须落进 unknown_overlaps。
"""

from pathlib import Path
import duckdb

OUT = Path(__file__).parent
OUT.mkdir(exist_ok=True)

# 坐标取自 data/geocode_cache.parquet（GCJ-02，门牌级）
COORD = {
    "浙江省杭州市拱墅区莫干山路111号": (30.3147, 120.1501),
    "浙江省杭州市西湖区文三路100号": (30.2810, 120.1320),
    "浙江省杭州市滨江区江陵路88号": (30.2052, 120.2152),
}

# ---- 物品台账：一件物品一行 ----
# 凭证号列为空即无凭证（D4），靠 descriptors 成实体。
# 坐标缺失是合法形态（票据/批号/赃物无处可落点），装配层标 mappable=False。
ITEMS = [
    # (物品名称, 物品类型, 凭证号, 所在地, 特征描述)
    ("黑色别克轿车", "车辆", "浙A12345", "浙江省杭州市拱墅区莫干山路111号", ""),
    ("文三路住宅", "房产", "杭西不动产权第2020001234号",
     "浙江省杭州市西湖区文三路100号", ""),
    ("建材销售发票", "票据", "033001900111-01234567", "", ""),
    ("耗材批次", "药品批号", "20210301-A", "", ""),
    ("黑色双肩包", "涉案物品", "", "", "黑色双肩包，内有账本"),
    ("银色U盘", "涉案物品", "", "", "银色U盘，容量64G，无编号"),
]

# ---- 持有流水：一次持有一行 ----
# 登记序号 = 台账录入顺序；与时间顺序不一致即错序线索。
# 结束日期为空 = 持续持有（开放区间，不是"到今天"，是"无证据表明已处置"）。
HOLDS = [
    # (物品名称, 凭证号, 持有人, 开始日期, 结束日期, 登记序号)
    ("黑色别克轿车", "浙A12345", "王五", "2019-03-01", "2021-06-30", 1),
    ("黑色别克轿车", "浙A12345", "李志强", "2021-07-01", "", 2),
    # 王五名下未过户，与李志强区间相交 → 重叠冲突（套牌／产权异常信号）
    ("黑色别克轿车", "浙A12345", "王五", "2021-08-01", "2022-01-31", 3),
    # 起止皆空 → 区间不可判定，落 unknown_overlaps，绝不进 conflicts
    ("黑色别克轿车", "浙A12345", "王五", "", "", 4),
    ("文三路住宅", "杭西不动产权第2020001234号", "张卫国", "2019-01-15", "2020-05-19", 1),
    ("文三路住宅", "杭西不动产权第2020001234号", "张卫国配偶", "2020-05-20", "", 2),
    # 错序：最先登记的（序号0）时间最晚
    ("建材销售发票", "033001900111-01234567", "张卫国", "2021-09-05", "2021-12-31", 0),
    ("建材销售发票", "033001900111-01234567", "李志强", "2021-09-02", "", 1),
    ("耗材批次", "20210301-A", "李志强妻弟", "2021-03-01", "", 1),
    ("黑色双肩包", "", "张卫国", "2020-03-10", "", 1),
    ("银色U盘", "", "李志强", "2020-03-17", "", 1),
    # 时刻级使用记录：卡口抓拍。登记数据（日期级）判不出"同时"，套牌信号
    # 只能靠这一层——同一车牌同一时段被两人分别使用，是信号不是噪声。
    # **刻意避开整点**："17:00:00" 全零会被判成 hour 档（不提精度），木桶
    # 取最弱档后整条链判不出重叠——整点陷阱，填数据时必须绕开。
    ("黑色别克轿车", "浙A12345", "王五", "2021-09-15 14:20:00", "2021-09-15 16:40:00", 5),
    ("黑色别克轿车", "浙A12345", "李志强", "2021-09-15 15:10:00", "2021-09-15 17:05:00", 6),
]


def main() -> None:
    con = duckdb.connect()
    con.execute("""
        CREATE TABLE items(
            物品名称 VARCHAR, 物品类型 VARCHAR, 凭证号 VARCHAR,
            所在地 VARCHAR, 特征描述 VARCHAR)
    """)
    con.executemany("INSERT INTO items VALUES (?,?,?,?,?)", ITEMS)
    rows = con.execute("""
        SELECT 物品名称, 物品类型, 凭证号, 所在地, 特征描述,
               CAST(NULL AS DOUBLE) AS 经度, CAST(NULL AS DOUBLE) AS 纬度
        FROM items
    """).fetchall()
    # 坐标按所在地回填；无地址保持 NULL（不补 0）
    with_coord = []
    for r in rows:
        lat, lng = COORD.get(r[3], (None, None))
        with_coord.append(r[:5] + (lng, lat))
    con.execute("CREATE TABLE items2 AS SELECT * FROM (VALUES (1)) WHERE FALSE")
    con.execute("""
        CREATE TABLE items_out(
            物品名称 VARCHAR, 物品类型 VARCHAR, 凭证号 VARCHAR,
            所在地 VARCHAR, 特征描述 VARCHAR, 经度 DOUBLE, 纬度 DOUBLE)
    """)
    con.executemany("INSERT INTO items_out VALUES (?,?,?,?,?,?,?)", with_coord)
    con.execute(f"COPY items_out TO '{OUT / '物品台账.parquet'}' (FORMAT PARQUET)")

    con.execute("""
        CREATE TABLE holds(
            物品名称 VARCHAR, 凭证号 VARCHAR, 持有人 VARCHAR,
            开始日期 VARCHAR, 结束日期 VARCHAR, 登记序号 INTEGER)
    """)
    con.executemany("INSERT INTO holds VALUES (?,?,?,?,?,?)", HOLDS)
    con.execute(f"COPY holds TO '{OUT / '物品持有登记.parquet'}' (FORMAT PARQUET)")
    con.close()
    print(f"已生成：{OUT / '物品台账.parquet'}（{len(ITEMS)} 件）"
          f" / {OUT / '物品持有登记.parquet'}（{len(HOLDS)} 条持有）")


if __name__ == "__main__":
    main()
